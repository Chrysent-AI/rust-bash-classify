#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
commands_dir="$repo_root/vendor/commands"
out="$repo_root/src/commands_data.rs"

if [[ ! -d "$commands_dir" ]]; then
  echo "missing vendored commands directory: $commands_dir" >&2
  exit 1
fi

{
  echo '// @generated by scripts/gen_commands_data.sh; do not edit by hand.'
  echo
  echo '/// Vendored built-in command definitions as `(name, relative_path, yaml_text)`.'
  echo 'pub const COMMANDS: &[(&str, &str, &str)] = &['
  while IFS= read -r path; do
    file=$(basename "$path")
    name=${file%.yaml}
    printf '    ("%s", "commands/%s", include_str!("../vendor/commands/%s")),\n' "$name" "$file" "$file"
  done < <(find "$commands_dir" -maxdepth 1 -type f -name '*.yaml' | LC_ALL=C sort)
  echo '];'
} > "$out"

if command -v rustfmt >/dev/null 2>&1; then
  rustfmt "$out"
fi
